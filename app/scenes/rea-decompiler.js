      ctx.strokeStyle = col;
      ctx.beginPath();
      if (side === 'L') ctx.arc(ring.cx, ring.cy, r, (deg - 3.5) * DEG, (deg + 3.5) * DEG);
      else ctx.arc(ring.cx, ring.cy, r, Math.PI + (deg - 3.5) * DEG, Math.PI + (deg + 3.5) * DEG);
